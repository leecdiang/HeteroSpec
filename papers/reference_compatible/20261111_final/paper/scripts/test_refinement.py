"""Figure/source preflight for the targeted refinement; no GPU or network.

Bounding boxes are generated by Matplotlib's raster renderer. They are screening
checks, not a replacement for inspection of embedded PGF figures and final pages.
"""
from pathlib import Path
import hashlib, json, re, unittest
P=Path(__file__).resolve().parents[1]

class RefinementChecks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fig=json.loads((P/'FIGURE_MANIFEST.json').read_text())
        cls.layout=json.loads((P/'generated/FIGURE_LAYOUT_CHECK.json').read_text())
        cls.data=json.loads((P/'generated/analysis.json').read_text())
    def test_every_statistical_export_has_one_axis(self):
        self.assertEqual(len(self.fig),8)
        self.assertTrue(all(f['axis_count']==1 for f in self.fig))
    def test_same_analysis_identity(self):
        expected=hashlib.sha256((P/'generated/analysis.json').read_bytes()).hexdigest()
        self.assertTrue(all(f['analysis_sha256']==expected for f in self.fig))
    def test_no_off_canvas_figure_text(self):
        self.assertTrue(all(not f['text_outside_canvas'] for f in self.layout))
    def test_figure_text_has_no_material_overlap(self):
        for f in self.layout:
            boxes=f['text_boxes']
            for i,a in enumerate(boxes):
                x0,y0,x1,y1=a['bbox_px']; area_a=max(0,x1-x0)*max(0,y1-y0)
                for b in boxes[i+1:]:
                    u0,v0,u1,v1=b['bbox_px']; area_b=max(0,u1-u0)*max(0,v1-v0)
                    overlap=max(0,min(x1,u1)-max(x0,u0))*max(0,min(y1,v1)-max(y0,v0))
                    self.assertLessEqual(overlap,.03*min(area_a,area_b)+.01,(f['figure'],a['text'],b['text']))
    def test_expected_figure_files_exist(self):
        for f in self.fig:
            for ext in ('pdf','svg','png'):
                self.assertTrue((P/'figures'/f'{f["file"]}.{ext}').is_file())
    def test_uncertain_factorial_markers_remain_neutral(self):
        # The exact two crossing intervals and source-driven encoding must coexist.
        uncertain=[(m,j) for m,f in self.data['factors'].items()
                   for j,r in enumerate(f['all_fixed_controls']) if r['interval'][0]<=1<=r['interval'][1]]
        self.assertEqual(set(uncertain),{('8B',1),('14B',1)})
        src=(P/'scripts/build_figures.py').read_text()
        self.assertIn('hollow=not supported',src)
        self.assertIn('if supported else GRAY',src)
    def test_all_six_q32_paths_and_four_equalwork_cells_retained(self):
        self.assertEqual(len(self.data['q32']['means']),6)
        self.assertEqual(len(self.data['equal_work']),4)
        self.assertGreater(self.data['q32']['draft_over_best_M'],1)
    def test_signed_cost_is_in_own_numeric_column(self):
        f=next(f for f in self.layout if f['figure']=='supp_width_cost')
        value=next(x for x in f['text_boxes'] if x['text']=='-2.792')
        label=next(x for x in f['text_boxes'] if x['text']=='Draft sync')
        self.assertGreater(value['bbox_px'][0],label['bbox_px'][2])
    def test_width_direction_labels_are_distinct(self):
        f={x['figure']:{y['text'] for y in x['text_boxes']} for x in self.layout}
        self.assertIn('Less time',f['width_equal'])
        self.assertIn('More time',f['width_live'])
        self.assertIn('1 = equal',f['width_equal']);self.assertIn('1 = equal',f['width_live'])
    def test_removed_defensive_examples(self):
        paths=list((P/'sections').glob('*.tex'))+[P/'supplement_body.tex']
        text='\n'.join(p.read_text() for p in paths)
        for s in ('manufacture equal lengths','without amortizing initialization away',
                  'manufacture a faster path','does not relabel'):
            self.assertNotIn(s,text)

if __name__=='__main__':unittest.main()
