"""Generate v0.7 projections exclusively from the frozen formal analyses."""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parents[1]
REPO = HERE.parents[2]
SOURCES = [('RTX', 'benchmarks/rtx_direct_id_v2/FORMAL_ANALYSIS.json', 'conditions',
            [('Batched', 'RTX_BATCHED_K2'), ('Serialized', 'RTX_SERIALIZED_K2')]),
           ('B', 'benchmarks/b570_direct_id_v1/FORMAL_ANALYSIS.json', 'paths',
            [('Fast', 'B570_FAST_K2'), ('Serialized', 'B570_SERIALIZED_K2')])]

def records():
    result = []
    for platform, source, key, paths in SOURCES:
        data = json.loads((REPO/source).read_text(encoding='utf-8'))
        for path, condition in paths:
            row = data[key][condition]
            result.append(dict(platform=platform, path=path, condition=condition,
                               source=source, exact_pairs=row['exact_pairs'],
                               exact_prompts=row['wholly_exact_prompts'], status=row['qualification']))
    return result

def tex():
    lines = ['% Generated by scripts/direct_id_values.py from frozen formal JSON; do not edit.']
    for row in records():
        prefix = 'DI'+row['platform']+row['path']
        for suffix, value in [('Pairs', row['exact_pairs']), ('Prompts', row['exact_prompts']), ('Status', row['status'])]:
            lines.append('\\newcommand{\\'+prefix+suffix+'}{'+str(value)+'}')
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    (HERE/'tables/direct_id_values.tex').write_text(tex(), encoding='utf-8', newline='\n')
    print('Generated 12 direct-ID macros from two formal analyses.')
